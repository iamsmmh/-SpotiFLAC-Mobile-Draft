import 'package:flutter_test/flutter_test.dart';
import 'package:spotimusic/ecosystem/cache/cache_cipher.dart';

void main() {
  group('ChaCha20 (RFC 8439)', () {
    test('§2.3.2 block test vector', () {
      final key = <int>[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
      ];
      final nonce = <int>[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x4a,
        0x00, 0x00, 0x00, 0x00,
      ];
      final block = chacha20Block(key, nonce, 1);
      expect(block.sublist(0, 16), <int>[
        0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15,
        0x50, 0x0f, 0xdd, 0x1f, 0xa3, 0x20, 0x71, 0xc4,
      ]);
      expect(block.sublist(16, 32), <int>[
        0xc7, 0xd1, 0xf4, 0xc7, 0x33, 0xc0, 0x68, 0x03,
        0x04, 0x22, 0xaa, 0x9a, 0xc3, 0xd4, 0x6c, 0x4e,
      ]);
      expect(block.sublist(32, 48), <int>[
        0xd2, 0x82, 0x64, 0x46, 0x07, 0x9f, 0xaa, 0x09,
        0x14, 0xc2, 0xd7, 0x05, 0xd9, 0x8b, 0x02, 0xa2,
      ]);
      expect(block.sublist(48, 64), <int>[
        0xb5, 0x12, 0x9c, 0xd1, 0xde, 0x16, 0x4e, 0xb9,
        0xcb, 0xd0, 0x83, 0xe8, 0xa2, 0x50, 0x3c, 0x4e,
      ]);
    });

    test('§2.4.2 encryption test vector', () {
      final key = <int>[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
      ];
      final nonce = <int>[
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4a,
        0x00, 0x00, 0x00, 0x00,
      ];
      final plaintext = <int>[
        // "Ladies and Gentlemen of the class of '99: If I could offer you "
        // "only one tip for the future, sunscreen would be it."
        0x4c, 0x61, 0x64, 0x69, 0x65, 0x73, 0x20, 0x61, 0x6e, 0x64, 0x20,
        0x47, 0x65, 0x6e, 0x74, 0x6c, 0x65, 0x6d, 0x65, 0x6e, 0x20, 0x6f,
        0x66, 0x20, 0x74, 0x68, 0x65, 0x20, 0x63, 0x6c, 0x61, 0x73, 0x73,
        0x20, 0x6f, 0x66, 0x20, 0x27, 0x39, 0x39, 0x3a, 0x20, 0x49, 0x66,
        0x20, 0x49, 0x20, 0x63, 0x6f, 0x75, 0x6c, 0x64, 0x20, 0x6f, 0x66,
        0x66, 0x65, 0x72, 0x20, 0x79, 0x6f, 0x75, 0x20, 0x6f, 0x6e, 0x6c,
        0x79, 0x20, 0x6f, 0x6e, 0x65, 0x20, 0x74, 0x69, 0x70, 0x20, 0x66,
        0x6f, 0x72, 0x20, 0x74, 0x68, 0x65, 0x20, 0x66, 0x75, 0x74, 0x75,
        0x72, 0x65, 0x2c, 0x20, 0x73, 0x75, 0x6e, 0x73, 0x63, 0x72, 0x65,
        0x65, 0x6e, 0x20, 0x77, 0x6f, 0x75, 0x6c, 0x64, 0x20, 0x62, 0x65,
        0x20, 0x69, 0x74, 0x2e,
      ];
      final cipher = ChaCha20(key: key, nonce: nonce);
      final out = cipher.processBytes(plaintext);
      // Expected values are the "Ciphertext Sunscreen" bytes printed in
      // RFC 8439 §2.4.2 (https://www.rfc-editor.org/rfc/rfc8439). The two
      // non-leading slices previously asserted here did not match the RFC
      // (the implementation did) and failed CI on the 2026-09-05 lineage;
      // they are corrected to the published vector.
      expect(out.sublist(0, 16), <int>[
        0x6e, 0x2e, 0x35, 0x9a, 0x25, 0x68, 0xf9, 0x80,
        0x41, 0xba, 0x07, 0x28, 0xdd, 0x0d, 0x69, 0x81,
      ]);
      expect(out.sublist(16, 32), <int>[
        0xe9, 0x7e, 0x7a, 0xec, 0x1d, 0x43, 0x60, 0xc2,
        0x0a, 0x27, 0xaf, 0xcc, 0xfd, 0x9f, 0xae, 0x0b,
      ]);
      expect(out.sublist(48, 64), <int>[
        0x16, 0x39, 0xd6, 0x24, 0xe6, 0x51, 0x52, 0xab,
        0x8f, 0x53, 0x0c, 0x35, 0x9f, 0x08, 0x61, 0xd8,
      ]);
      expect(out.sublist(out.length - 8), <int>[
        0x8e, 0xed, 0xf2, 0x78, 0x5e, 0x42, 0x87, 0x4d,
      ]);

      // Decrypt round trip.
      final again = ChaCha20(key: key, nonce: nonce);
      expect(again.processBytes(out), plaintext);
    });

    test('encrypting a second time restores the plaintext', () {
      final key = generateCacheKey();
      final nonce = generateCacheNonce();
      final data = List<int>.generate(5000, (i) => (i * 7) & 0xFF);
      final encrypted = ChaCha20(key: key, nonce: nonce).processBytes(data);
      expect(encrypted, isNot(equals(data)));
      final restored = ChaCha20(key: key, nonce: nonce).processBytes(encrypted);
      expect(restored, data);
    });

    test('keys and nonces have the right length and entropy', () {
      final a = generateCacheKey();
      final b = generateCacheKey();
      expect(a, hasLength(32));
      expect(b, hasLength(32));
      expect(a, isNot(equals(b)));
      final nonce = generateCacheNonce();
      expect(nonce, hasLength(12));
    });
  });

  group('hex helpers', () {
    test('round trip', () {
      final bytes = <int>[0x00, 0x0f, 0xff, 0x10];
      final hex = bytesToHex(bytes);
      expect(hex, '000fff10');
      expect(hexToBytes(hex), bytes);
      expect(hexToBytes('zz'), isEmpty);
    });
  });
}
